(function() {
    'use strict';
    
    document.addEventListener('DOMContentLoaded', function() {
        const titleInput = document.getElementById('title');
        const metaTitleInput = document.getElementById('meta_title');
        
        if (titleInput && metaTitleInput) {
            titleInput.addEventListener('input', function() {
                if (!metaTitleInput.value || metaTitleInput.dataset.autoGenerated === 'true') {
                    metaTitleInput.value = this.value;
                    metaTitleInput.dataset.autoGenerated = 'true';
                }
            });
            
            metaTitleInput.addEventListener('input', function() {
                this.dataset.autoGenerated = 'false';
            });
        }
        
        DKApps.initSlugField('title', 'slug');
        DKApps.initImagePreview('image', 'imagePreview', 'removeImage');
        DKApps.initFilePreview('file', 'fileInfo', 'fileName', 'fileSize', 'removeFile');
        DKApps.initDeleteExistingImage();
        DKApps.initDeleteExistingFile();
        
        let attempts = 0;
        const maxAttempts = 10;
        const checkInterval = setInterval(function() {
            attempts++;
            const tagsInput = document.getElementById('tags');
            const choicesContainer = document.querySelector('.choices');
            
            if ((tagsInput && (tagsInput.choicesInstance || tagsInput._choices)) || choicesContainer || attempts >= maxAttempts) {
                clearInterval(checkInterval);
                initTagSuggestions();
            }
        }, 200);
        
        const announcementForm = document.getElementById('announcementForm');
        const submitBtn = document.getElementById('submitBtn');
        
        if (announcementForm && submitBtn) {
            announcementForm.addEventListener('submit', function(e) {
                if (!announcementForm.checkValidity()) {
                    e.preventDefault();
                    e.stopPropagation();
                }
                
                announcementForm.classList.add('was-validated');
                
                const editorInstance = window.ckeditorInstances ? window.ckeditorInstances['editor'] : null;
                
                if (editorInstance) {
                    const content = editorInstance.getData();
                    const contentTextarea = document.getElementById('content');
                    const contentError = document.getElementById('contentError');
                    
                    if (contentTextarea) {
                        contentTextarea.value = content;
                    }
                    
                    if (!content || content.trim() === '' || content === '<p>&nbsp;</p>' || content === '<p></p>') {
                        e.preventDefault();
                        
                        if (contentError) {
                            contentError.style.display = 'block';
                        }
                        
                        const editorElement = document.getElementById('editor');
                        if (editorElement) {
                            editorElement.scrollIntoView({ behavior: 'smooth', block: 'center' });
                        }
                        
                        return false;
                    } else {
                        if (contentError) {
                            contentError.style.display = 'none';
                        }
                        
                        submitBtn.disabled = true;
                        submitBtn.innerHTML = `
                            <span class="d-flex align-items-center">
                                <span class="spinner-border spinner-border-sm flex-shrink-0" role="status">
                                    <span class="visually-hidden">Loading...</span>
                                </span>
                                <span class="flex-grow-1 ms-2">Menyimpan...</span>
                            </span>
                        `;
                    }
                }
            });
        }
    });
        
    function initTagSuggestions() {
        const tagSuggestions = document.querySelectorAll('.tag-suggestion');
        const tagsInput = document.getElementById('tags');
        
        if (!tagSuggestions.length || !tagsInput) return;
        
        tagSuggestions.forEach(button => {
            button.addEventListener('click', function(e) {
                e.preventDefault();
                const tagValue = this.getAttribute('data-tag');
                
                let choicesInstance = 
                    tagsInput.choicesInstance || 
                    (window.choicesInstances && window.choicesInstances[tagsInput.id]) || 
                    tagsInput._choices || 
                    ((tagsInput.closest('.choices') || {}).choices);
                
                if (choicesInstance) {
                    try {
                        const currentValues = choicesInstance.getValue(true);
                        const tagExists = Array.isArray(currentValues) ? 
                            currentValues.includes(tagValue) : 
                            currentValues === tagValue;
                        
                        if (!tagExists) {
                            try {
                                choicesInstance.setChoiceByValue(tagValue);
                            } catch (e) {
                                const newValues = Array.isArray(currentValues) ? 
                                    [...currentValues, tagValue] : 
                                    [tagValue];
                                choicesInstance.setValue(newValues);
                            }
                            
                            updateButtonState(this, 'btn-success', '<i class="ri-check-line"></i> ' + tagValue);
                        } else {
                            updateButtonState(this, 'btn-warning', '<i class="ri-information-line"></i> Sudah ada');
                        }
                    } catch (error) {
                        handleFallback(tagsInput, tagValue, this);
                    }
                } else {
                    handleFallback(tagsInput, tagValue, this);
                }
            });
        });
        
        function updateButtonState(button, addClass, html) {
            button.classList.remove('btn-outline-primary');
            button.classList.add(addClass);
            button.innerHTML = html;
            
            setTimeout(() => {
                button.classList.remove(addClass);
                button.classList.add('btn-outline-primary');
                button.innerHTML = button.getAttribute('data-tag');
            }, 1000);
        }
        
        function handleFallback(input, tagValue, button) {
            const currentValue = input.value;
            const tags = currentValue ? currentValue.split(',').map(t => t.trim()).filter(t => t) : [];
            
            if (!tags.includes(tagValue)) {
                tags.push(tagValue);
                input.value = tags.join(',');
                input.dispatchEvent(new Event('change', { bubbles: true }));
                
                const choicesInner = document.querySelector('.choices__inner');
                if (choicesInner) {
                    let itemsList = choicesInner.querySelector('.choices__list--multiple');
                    if (!itemsList) {
                        itemsList = document.createElement('div');
                        itemsList.className = 'choices__list choices__list--multiple';
                        choicesInner.insertBefore(itemsList, choicesInner.firstChild);
                    }
                    
                    const itemDiv = document.createElement('div');
                    itemDiv.className = 'choices__item choices__item--selectable';
                    itemDiv.setAttribute('data-item', '');
                    itemDiv.setAttribute('data-id', Date.now());
                    itemDiv.setAttribute('data-value', tagValue);
                    itemDiv.setAttribute('data-deletable', '');
                    
                    const removeBtn = document.createElement('button');
                    removeBtn.type = 'button';
                    removeBtn.className = 'choices__button';
                    removeBtn.setAttribute('data-button', '');
                    removeBtn.textContent = 'Remove item';
                    
                    removeBtn.addEventListener('click', function(e) {
                        e.preventDefault();
                        const currentValue = input.value;
                        const tags = currentValue ? currentValue.split(',').map(t => t.trim()).filter(t => t) : [];
                        const newTags = tags.filter(t => t !== tagValue);
                        input.value = newTags.join(',');
                        itemDiv.remove();
                    });
                    
                    itemDiv.textContent = tagValue;
                    itemDiv.appendChild(removeBtn);
                    itemsList.appendChild(itemDiv);
                }
                
                updateButtonState(button, 'btn-success', '<i class="ri-check-line"></i> ' + tagValue);
            } else {
                updateButtonState(button, 'btn-warning', '<i class="ri-information-line"></i> Sudah ada');
            }
        }
    }
    
})();